    public static function config(array $settings): array
    {
        $raw=$settings['v5_locales_published']??null;
        $data=is_array($raw)?$raw:(is_string($raw)?json_decode($raw,true):null);
        if(!is_array($data))return ['enabled'=>['en'],'default'=>'en'];
        $enabled=array_values(array_unique(array_intersect(['en','ar'],array_filter((array)($data['enabled']??[]),'is_string'))));
        if(!$enabled)$enabled=['en'];
        $default=(string)($data['default']??'en');
        if(!in_array($default,$enabled,true))$default=$enabled[0];
        return ['enabled'=>$enabled,'default'=>$default];
    }
    public static function current(?array $settings=null): string
    {
        if(self::$current!==null)return self::$current;
        $cfg=self::config($settings??(function_exists('store_runtime_settings')?\store_runtime_settings():[]));
        $cookie='COMMERCE_LANG_'.substr(hash('sha256',defined('BASE_PATH')?BASE_PATH:'/'),0,8);
        $requested=$_GET['lang']??null;
        $candidate=is_string($requested)?$requested:(string)($_COOKIE[$cookie]??'');
        if(!in_array($candidate,$cfg['enabled'],true))$candidate=$cfg['default'];
        self::$current=$candidate;
        if(is_string($requested)&&in_array($requested,$cfg['enabled'],true)&&!headers_sent()){
            $path=defined('BASE_PATH')&&BASE_PATH!==''?BASE_PATH.'/':'/';
            setcookie($cookie,$candidate,['expires'=>time()+31536000,'path'=>$path,'secure'=>function_exists('web_request_is_https')?\web_request_is_https():false,'httponly'=>true,'samesite'=>'Lax']);
        }
        return $candidate;
    }
    public static function resetForTest(): void {self::$current=null;self::$translationCache=[];self::$translationsUnavailable=false;}
    public static function direction(?string $locale=null): string {return ($locale??self::current())==='ar'?'rtl':'ltr';}
    public static function switchUrl(string $lang,?string $requestUri=null): string
    {
        $uri=$requestUri??(string)($_SERVER['REQUEST_URI']??'/');
        $path=parse_url($uri,PHP_URL_PATH);
        if(!is_string($path)||$path===''||str_starts_with($path,'//'))$path=function_exists('route_url')?\route_url('index.php'):'/';
        $base=defined('BASE_PATH')?rtrim((string)BASE_PATH,'/'):'';
        if($base!==''&&$path!==$base&&!str_starts_with($path,$base.'/'))$path=$base.'/index.php';
        $query=parse_url($uri,PHP_URL_QUERY);$params=[];
        if(is_string($query))parse_str($query,$params);
        unset($params['lang']);$params['lang']=in_array($lang,['en','ar'],true)?$lang:'en';
        return $path.'?'.http_build_query($params,'','&',PHP_QUERY_RFC3986);
    }
    public static function tr(string $text,?string $locale=null): string
    {
        $lang=$locale??self::current();if($lang!=='ar')return $text;
        return self::arabic()[$text]??$text;
    }
    /** Translate customer-facing messages only at the presentation/API boundary. */
    public static function publicMessage(string $message, ?string $locale=null): string
    {
        if(($locale??self::current())!=='ar'||$message==='')return $message;
        $translated=self::tr($message,'ar');
        if($translated!==$message)return $translated;
        // Keep historic product names, order numbers and amounts untouched.
        if(preg_match('/^Return request #(\d+) was submitted for review\.$/D',$message,$m))return 'تم إرسال طلب الإرجاع رقم #'.$m[1].' للمراجعة.';
        if(preg_match('/^The (\d+)-day return window for this order has ended\.$/D',$message,$m))return 'انتهت مهلة الإرجاع لهذا الطلب ('.$m[1].' يوماً).';
        if(preg_match('/^(.+) · (.+) only has (\d+) left in stock\.$/Du',$message,$m))return $m[1].' · '.$m[2].': المتبقي في المخزون '.$m[3].' فقط.';
        if(preg_match('/^(.+) is no longer available\.$/Du',$message,$m))return $m[1].': لم يعد متوفراً.';
        if(preg_match('/^Return quantity is higher than the remaining quantity for (.+)\.$/Du',$message,$m))return 'كمية الإرجاع تتجاوز الكمية المتاحة للمنتج '.$m[1].'.';
        return $message;
    }

