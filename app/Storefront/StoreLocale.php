    /** Batch load translations without modifying the source rows or order snapshots. */
    public static function rows(array $rows,string $type): array
    {
        if(self::current()!=='ar'||!in_array($type,['product','category','brand','department','section','section_item'],true))return $rows;
        $ids=[];foreach($rows as $row){$id=(int)($row['id']??0);if($id>0)$ids[$id]=$id;}
        if($ids&&!self::$translationsUnavailable){
            $pending=array_values(array_filter($ids,static fn($id)=>!isset(self::$translationCache[$type][$id])));
            if($pending){
                foreach($pending as $id)self::$translationCache[$type][$id]=[];
                try{
                    $placeholders=implode(',',array_fill(0,count($pending),'?'));
                    $query=\db()->prepare("SELECT entity_id,field_key,text_value FROM store_entity_translations WHERE entity_type=? AND locale='ar' AND entity_id IN ($placeholders)");
                    $query->execute(array_merge([$type],$pending));
                    foreach($query->fetchAll(\PDO::FETCH_ASSOC) as $value){
                        self::$translationCache[$type][(int)$value['entity_id']][(string)$value['field_key']]=(string)$value['text_value'];
                    }
                }catch(\Throwable){self::$translationsUnavailable=true;}
            }
        }
        foreach($rows as &$row){
            if(!is_array($row))continue;
            foreach(['name','description','short_description','seo_title','seo_description','title','subtitle','eyebrow','cta_label'] as $field){
                $translated=self::$translationCache[$type][(int)($row['id']??0)][$field]??null;
                $inline=$row[$field.'_ar']??null;
                // Homepage Builder owns its dedicated Arabic fields. Prefer them when set;
                // older translations remain as a fallback for legacy content.
                if(in_array($type,['section','section_item'],true)&&is_string($inline)&&trim($inline)!=='')$translated=$inline;
                elseif(!is_string($translated)||trim($translated)==='')$translated=$inline;
                if(is_string($translated)&&trim($translated)!=='')$row[$field]=$translated;
            }
            if(isset($row['brand_name_ar'])&&trim((string)$row['brand_name_ar'])!=='')$row['brand_name']=$row['brand_name_ar'];
        }unset($row);
        return $rows;
    }
